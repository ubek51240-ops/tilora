  function currentLang() {
    let lang = null;
    try {
      if (typeof window.getCurrentLang === "function") lang = window.getCurrentLang();
      if (!lang) lang = localStorage.getItem("tilora_lang");
    } catch (_) {}
    return DICT[lang] ? lang : "uz";
  }

  /** T(key, fallbackUz, vars?) — tarjima; {name} shablonlari vars orqali almashtiriladi. */
  window.T = function (key, fallbackUz, vars) {
    const lang = currentLang();
    let s = (DICT[lang] && DICT[lang][key]);
    if (s === undefined) s = DICT.uz[key];
    if (s === undefined) s = (fallbackUz === undefined || fallbackUz === null) ? key : fallbackUz;
    if (vars && typeof vars === "object") {
      Object.keys(vars).forEach(k => { s = String(s).split("{" + k + "}").join(String(vars[k])); });
    }
    return s;
  };
  window.EXT_I18N_DICT = DICT;
  window.getExtLang = currentLang;

  /** Statik elementlar ([data-i18n-ext], [data-i18n-ext-ph], [data-i18n-ext-title]) va dinamik ekranlar. */
  window.applyExtI18n = function () {
    document.querySelectorAll("[data-i18n-ext]").forEach(el => {
      const key = el.getAttribute("data-i18n-ext");
      if (!key) return;
      const fb = el.getAttribute("data-i18n-ext-uz") || el.textContent;
      if (!el.hasAttribute("data-i18n-ext-uz")) el.setAttribute("data-i18n-ext-uz", el.textContent.trim());
      el.textContent = window.T(key, fb.trim());
    });
    document.querySelectorAll("[data-i18n-ext-ph]").forEach(el => {
      el.setAttribute("placeholder", window.T(el.getAttribute("data-i18n-ext-ph"), el.getAttribute("placeholder") || ""));
    });
    document.querySelectorAll("[data-i18n-ext-title]").forEach(el => {
      el.setAttribute("title", window.T(el.getAttribute("data-i18n-ext-title"), el.getAttribute("title") || ""));
    });
    document.documentElement.setAttribute("data-ext-lang", currentLang());
    // Dinamik ekranlar (student_ext.js va dynamics.js o'zlari keshdan qayta chizadi)
    try { if (typeof window.rerenderStudentExt === "function") window.rerenderStudentExt(); } catch (e) { console.warn("[i18n_ext] rerenderStudentExt:", e); }
    try { if (typeof window.rerenderDynamics === "function") window.rerenderDynamics(); } catch (e) { console.warn("[i18n_ext] rerenderDynamics:", e); }
  };

  function wrapSwitchLanguage() {
    const orig = window.switchLanguage;
    if (typeof orig !== "function" || orig.__extWrapped) return;
    const wrapped = function (lang) {
      const r = orig.apply(this, arguments);
      try { window.applyExtI18n(); } catch (e) { console.warn("[i18n_ext] applyExtI18n:", e); }
      return r;
    };
    wrapped.__extWrapped = true;
    window.switchLanguage = wrapped;
  }

  // dissertation_features.js bu skriptdan oldin yuklanadi — darhol o'raymiz; ehtiyot uchun DOMContentLoaded da ham.
  wrapSwitchLanguage();
  document.addEventListener("DOMContentLoaded", () => {
    wrapSwitchLanguage();
    // Asl applyTranslations() DOMContentLoaded da ishlaydi (oldin ro'yxatga olingan) — bizniki undan keyin.
    setTimeout(() => { try { window.applyExtI18n(); } catch (_) {} }, 0);
  });
